def hero(kicker,title,subtitle):
    st.markdown(f'<div class="eyebrow">{html.escape(kicker)}</div><div class="hero">{html.escape(title)}</div><div class="subtitle">{html.escape(subtitle)}</div>',unsafe_allow_html=True)

def reading(text):
    # Escape first; only add formatting tags generated by us. No link/image interpretation.
    text=html.escape(text)
    text=re.sub(r'\*\*(.+?)\*\*',r'<strong>\1</strong>',text)
    blocks=[]
    for paragraph in text.split('\n\n'):
        if paragraph.startswith('#'):
            blocks.append('<h3>'+paragraph.lstrip('# ').replace('\n','<br>')+'</h3>')
        else:blocks.append('<p>'+paragraph.replace('\\\n','\n').replace('\n','<br>')+'</p>')
    st.markdown('<div class="reading">'+''.join(blocks)+'</div>',unsafe_allow_html=True)

def empty(text):st.markdown('<div class="empty">'+html.escape(text)+'</div>',unsafe_allow_html=True)
